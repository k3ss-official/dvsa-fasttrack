export function factsForTopic(topic: TopicId) {
  return FACTS.filter((f) => f.topic === topic);
}

export function factById(id: string) {
  return FACTS.find((f) => f.id === id);
}

export function factToQuestion(f: Fact): TheoryQuestion {
  return {
    id: f.id,
    domain: f.domain,
    stem: f.prompt,
    options: f.options,
    correctIndex: f.correctIndex,
    rationale: `${f.rationale} ${f.teach}`,
    reference: f.reference,
    faultIfWrong: f.faultIfWrong,
  };
}

export const FACT_QUESTIONS: TheoryQuestion[] = FACTS.map(factToQuestion);
